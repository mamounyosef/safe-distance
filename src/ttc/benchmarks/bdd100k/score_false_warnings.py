"""False warnings per hour on BDD100K normal driving, next to crashes warned on Nexar (CPU only).

BADAS-Open's live readings (every 0.5 s, badas_modal.py --series):
    BDD100K   608 normal-driving clips (about 6.7 h): every warning is false
    Nexar     Public half of the test set only: share of collision clips warned
              in the last 4 s before the event (the Private half stays untouched)
A warning = probability over the threshold for CONFIRM readings in a row; a
run of such readings counts as one warning episode.

RUN IT (from the repo root, after badas_modal.py --series for both datasets):

    .venv\\Scripts\\python.exe src\\ttc\\benchmarks\\bdd100k\\score_false_warnings.py

Writes results/false_warnings.json and FALSE_WARNINGS.md (generated from it).
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "nexar"))
from score_badas_series import CONFIRMS, COUNT_WINDOW_S, THRESHOLDS, badas_episodes, metadata  # noqa: E402

# ---- CONFIG ----
BDD_SERIES = HERE / "results" / "badas_series.json"
NEXAR_SERIES = HERE.parent / "nexar" / "results" / "test1" / "badas_series.json"
SOLUTION = Path(r"C:\safe-distance-data\nexar\meta\solution.csv")
OUT = HERE / "results"
# ----------------


def main() -> None:
    bdd = json.loads(BDD_SERIES.read_text())
    nexar = json.loads(NEXAR_SERIES.read_text())
    meta = metadata()
    public = {r["id"] for r in csv.DictReader(SOLUTION.open()) if r["Usage"] == "Public"}
    pos = {c: s for c, s in nexar.items() if c in public and meta[c]["positive"] and s}
    bdd_hours = sum(s[-1][0] - s[0][0] + 0.5 for s in bdd.values() if s) / 3600   # time covered by readings

    rows = []
    for thr in THRESHOLDS:
        for c in CONFIRMS:
            false = sum(len(badas_episodes(s, thr, c)) for s in bdd.values())
            warned = 0
            for cid, s in pos.items():
                end = s[-1][0]
                event = end + meta[cid]["tta"]
                if any(event - COUNT_WINDOW_S <= t <= end for t in badas_episodes(s, thr, c)):
                    warned += 1
            rows.append({"threshold": thr, "in_a_row": c, "bdd_false_warnings": false,
                         "bdd_false_per_hour": round(false / bdd_hours, 1),
                         "nexar_public_crashes_warned": round(warned / len(pos), 3)})
    res = {"bdd_clips": len(bdd), "bdd_hours": round(bdd_hours, 2), "nexar_public_collisions": len(pos), "rows": rows}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "false_warnings.json").write_text(json.dumps(res, indent=1))
    lines = ["# BADAS-Open: false warnings on BDD100K vs crashes warned on Nexar", "",
             "Generated by score_false_warnings.py from false_warnings.json. Do not edit by hand.", "",
             f"BDD100K: {res['bdd_clips']} normal-driving clips, {res['bdd_hours']} h covered by readings. "
             f"Nexar: {res['nexar_public_collisions']} collision clips of the Public half "
             f"(warning in the last {COUNT_WINDOW_S:g} s before the event).", "",
             "| Warn when risk > | Readings in a row | Crashes warned (Nexar Public) | "
             "False warnings per hour (BDD100K) |", "|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['threshold']} | {r['in_a_row']} | {r['nexar_public_crashes_warned'] * 100:.0f}% | "
                     f"{r['bdd_false_per_hour']} ({r['bdd_false_warnings']}) |")
    (OUT / "FALSE_WARNINGS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
